package qapi

import (
	"fmt"
	"sort"
	"strings"
)

func (g *Generator) genTypes() error {
	var sb strings.Builder
	sb.WriteString("// Code generated by qapi-gen. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("// QEMU version: %s\n\n", g.Version))
	sb.WriteString(fmt.Sprintf("package %s\n\n", g.Package))

	// Generate Enums
	enumNames := make([]string, 0, len(g.Schema.Enums))
	for name := range g.Schema.Enums {
		enumNames = append(enumNames, name)
	}
	sort.Strings(enumNames)

	for _, name := range enumNames {
		enumDef := g.Schema.Enums[name]
		enumTypeName := toPascalCase(enumDef.Name)
		sb.WriteString(fmt.Sprintf("// %s corresponds to QAPI enum %s\n", enumTypeName, enumDef.Name))
		sb.WriteString(fmt.Sprintf("type %s string\n\n", enumTypeName))
		sb.WriteString("const (\n")
		prefix := getEnumPrefix(enumDef.Name)
		for _, val := range enumDef.Data {
			constName := prefix + toPascalCase(val.Name)
			sb.WriteString(fmt.Sprintf("\t%s %s = %q\n", constName, enumTypeName, val.Name))
		}
		sb.WriteString(")\n\n")
	}

	// Generate Structs
	structNames := make([]string, 0, len(g.Schema.Structs))
	for name := range g.Schema.Structs {
		structNames = append(structNames, name)
	}
	sort.Strings(structNames)

	for _, name := range structNames {
		structDef := g.Schema.Structs[name]
		structTypeName := toPascalCase(structDef.Name)
		sb.WriteString(fmt.Sprintf("// %s corresponds to QAPI struct %s\n", structTypeName, structDef.Name))
		sb.WriteString(fmt.Sprintf("type %s struct {\n", structTypeName))

		fieldNames := make([]string, 0, len(structDef.Data))
		for fieldName := range structDef.Data {
			fieldNames = append(fieldNames, fieldName)
		}
		sort.Strings(fieldNames)

		for _, fieldName := range fieldNames {
			fieldDef := structDef.Data[fieldName]
			goFieldName := toPascalCase(strings.TrimPrefix(fieldName, "*"))
			goType := toGoType(fieldDef.Type)
			jsonTag := strings.TrimPrefix(fieldName, "*")
			sb.WriteString(fmt.Sprintf("\t%s %s `json:\"%s,omitempty\"` \n", goFieldName, goType, jsonTag))
		}
		sb.WriteString("}\n\n")
	}

	return g.writeFile("types_gen.go", sb.String())
}

func getEnumPrefix(enumName string) string {
	switch enumName {
	case "MigrationCapability":
		return "MigCap"
	default:
		return toPascalCase(enumName)
	}
}

func toPascalCase(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool {
		return r == '-' || r == '_' || r == '.'
	})
	for i, p := range parts {
		if strings.ToLower(p) == "ram" {
			parts[i] = "RAM"
		} else if strings.ToLower(p) == "xbzrle" {
			parts[i] = "XBZRLE"
		} else if strings.ToLower(p) == "rdma" {
			parts[i] = "RDMA"
		} else if strings.ToLower(p) == "fd" {
			parts[i] = "FD"
		} else if len(p) > 0 {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func toGoType(qapiType string) string {
	switch qapiType {
	case "str":
		return "string"
	case "bool":
		return "bool"
	case "int", "int8", "int16", "int32", "int64":
		return "int64"
	case "uint8", "uint16", "uint32", "uint64":
		return "uint64"
	case "number":
		return "float64"
	case "any":
		return "interface{}"
	default:
		return toPascalCase(qapiType)
	}
}
