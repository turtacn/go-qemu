package qapi

import (
	"fmt"
	"strings"
)

func (g *Generator) genCommands() error {
	var sb strings.Builder
	sb.WriteString("// Code generated by qapi-gen. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("// QEMU version: %s\n\n", g.Version))
	sb.WriteString(fmt.Sprintf("package %s\n\n", g.Package))

	sb.WriteString("// Commands map lists all available command names in this QEMU version.\n")
	sb.WriteString("var Commands = []string{\n")
	for name := range g.Schema.Commands {
		sb.WriteString(fmt.Sprintf("\t%q,\n", name))
	}
	sb.WriteString("}\n")

	return g.writeFile("commands_gen.go", sb.String())
}
