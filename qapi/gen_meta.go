package qapi

import (
	"fmt"
	"sort"
	"strings"
)

func (g *Generator) genMeta() error {
	var sb strings.Builder
	sb.WriteString("// Code generated by qapi-gen. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("package %s\n\n", g.Package))

	sb.WriteString("// CommandSet contains all defined QMP command names for runtime Feature Gate cross-checking.\n")
	sb.WriteString("var CommandSet = map[string]struct{}{\n")

	// Sort commands for deterministic output
	cmds := make([]string, 0, len(g.Schema.Commands))
	for cmdName := range g.Schema.Commands {
		cmds = append(cmds, cmdName)
	}
	sort.Strings(cmds)

	for _, cmdName := range cmds {
		sb.WriteString(fmt.Sprintf("\t%q: {},\n", cmdName))
	}
	sb.WriteString("}\n\n")

	sb.WriteString(fmt.Sprintf("// Version indicates the QEMU version of this generated code.\nconst Version = %q\n", g.Version))

	return g.writeFile("schema_meta_gen.go", sb.String())
}
